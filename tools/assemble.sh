#!/usr/bin/env bash
# Stitch the beat clips, hold the final frame, then composite the signature overlay.
# usage: tools/assemble.sh <slug> [ambient.m4a]
#
# Expects public/clips/beat1.mp4, beat3.mp4, beat4.mp4, beat5.mp4, beat6.mp4
# (beat2 was cut for budget). Mixed 1080p/720p sources are normalised to 1080x1920.
set -euo pipefail
cd "$(dirname "$0")/.."
SLUG="${1:-first-rain}"; AMBIENT="${2:-}"
FPS=30; SIG_SECONDS=3.0; HOLD_SECONDS=3.0
BEATS=(1 3 4 5 6)

for i in "${BEATS[@]}"; do
  [ -f "public/clips/beat$i.mp4" ] || { echo "missing public/clips/beat$i.mp4" >&2; exit 1; }
done

# Normalise every clip to the same canvas/fps so concat is safe across resolutions.
mkdir -p public/clips/norm
: > public/clips/list.txt
for i in "${BEATS[@]}"; do
  ffmpeg -v error -y -i "public/clips/beat$i.mp4" \
    -vf "scale=1080:1920:force_original_aspect_ratio=decrease,pad=1080:1920:(ow-iw)/2:(oh-ih)/2,fps=$FPS,setsar=1" \
    -an -c:v libx264 -crf 17 -pix_fmt yuv420p "public/clips/norm/beat$i.mp4"
  echo "file 'norm/beat$i.mp4'" >> public/clips/list.txt
done

ffmpeg -v error -y -f concat -safe 0 -i public/clips/list.txt -an -c:v libx264 -crf 17 -pix_fmt yuv420p public/cut_raw.mp4

# Hold the last frame so the signature has room to land and the Short clears ~33s.
ffmpeg -v error -y -i public/cut_raw.mp4 \
  -vf "tpad=stop_mode=clone:stop_duration=$HOLD_SECONDS" \
  -an -c:v libx264 -crf 17 -pix_fmt yuv420p public/cut.mp4
rm -f public/cut_raw.mp4

DUR=$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 public/cut.mp4)
FRAMES=$(python3 -c "print(round($DUR * $FPS))")
SIGF=$(python3 -c "print(round($SIG_SECONDS * $FPS))")

AUDIO_JSON="null"
if [ -n "$AMBIENT" ]; then cp "$AMBIENT" public/ambient.m4a; AUDIO_JSON='"ambient.m4a"'; fi

cat > src/active/meta.ts <<EOF
// GENERATED by tools/assemble.sh — do not edit by hand.
export const META = {
  "slug": "$SLUG",
  "fps": $FPS,
  "videoFile": "cut.mp4",
  "audioFile": $AUDIO_JSON,
  "durationInFrames": $FRAMES,
  "signatureFrames": $SIGF
} as const;
EOF

npx tsc --noEmit
mkdir -p "out/$SLUG"
npx remotion render src/index.ts Episode "out/$SLUG/raw.mp4" \
  --browser-executable=/opt/pw-browsers/chromium \
  --codec=h264 --crf=18 --audio-codec=aac --audio-bitrate=192k --log=error
ffmpeg -v error -y -i "out/$SLUG/raw.mp4" -c copy -movflags +faststart "out/$SLUG/$SLUG.mp4"
rm -f "out/$SLUG/raw.mp4"
echo "✓ out/$SLUG/$SLUG.mp4  (${DUR}s, $FRAMES frames)"
